"""Generates plugin/companions/data/companion_sets.txt and plugin/companions/companion_sets_default.h (campaign gap G34).

    python -I plugin/companions/proof/gen_sets.py            write both files
    python -I plugin/companions/proof/gen_sets.py --check    exit 1 when either file is out of date (needs out/questdata for the script list)

Inputs
  plugin/dialogue/data/follower_rules.txt   every placed form of every companion (the same table the dialogue registry uses)
  out/questdata/scripts.json.gz             the game's scripts: a quest / object script that READS the hired flags of the follower quests (VNPCFollowers,
                                            NVDLC01Followers, NVDLC02FollowersQuest) and never writes a hired / fired flag or SetPlayerTeammate is a "mover or gate"
                                            (Fort entry and exit, Yes Man's Dam start, the Lonesome Road door, the barks): it must see the hired flags of the
                                            WHOLE party, so it is listed as `view-party`. A script that hires or fires reads the acting player's own.

Output rules (see synccore/social/slots.h): `group` = one companion at a time per player (Dead Money, Honest Hearts), `party` = always a party companion
(none by default: the rules engine's owner=party names ED-E in Lonesome Road), `view-party` = the scripts above.
"""
import gzip
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
FOLLOWERS = ROOT / "plugin" / "dialogue" / "data" / "follower_rules.txt"
SCRIPTS = ROOT / "out" / "questdata" / "scripts.json.gz"
OUT_TXT = ROOT / "plugin" / "companions" / "data" / "companion_sets.txt"
OUT_H = ROOT / "plugin" / "companions" / "companion_sets_default.h"

# one companion at a time per player: the Dead Money three (Dog and God are two forms of one), the two Honest Hearts companions that swap
GROUPS = [("deadmoney", "NVDLC01Followers", ["Dean", "Christine", "Dog"]),
          ("honesthearts", "NVDLC02FollowersQuest", ["FollowsChalk", "WakingCloud"])]

HIRED = re.compile(r"\b(?:VNPCFollowers|NVDLC01Followers|NVDLC02FollowersQuest)\.(?:b?\w*Hired)\b|\bb(?:Boone|Cass|Veronica|Lily|EDE|Raul|Arcade|Rex)Hired\b", re.I)
WRITES = re.compile(r"set\s+\w+\.(?:b?\w*(?:Hired|Fired))\s+to\b|SetPlayerTeammate", re.I)


def follower_groups():
    quests = {}
    cur = None
    for line in FOLLOWERS.read_text(encoding="utf-8").splitlines():
        if line.startswith("quest "):
            cur = line.split()[2]
            quests[cur] = {}
        elif line.startswith("companion ") and cur:
            parts = line.split()
            refs = [t[5:] for t in parts if t.startswith("refs=")][0]
            quests[cur][parts[1]] = refs
    out = []
    for name, quest, members in GROUPS:
        refs = ",".join(quests[quest][m] for m in members)
        out.append((name, refs))
    return out


def mover_scripts():
    d = json.load(gzip.open(SCRIPTS))
    names = []
    for x in d:
        src = x["script"].get("source", "") if isinstance(x["script"], dict) else ""
        if HIRED.search(src) and not WRITES.search(src):
            names.append(x["edid"])
    return sorted(set(names), key=str.lower)


def build(scripts):
    lines = ["# generated by plugin/companions/proof/gen_sets.py; do not edit",
             "# G34: companion set pieces (synccore/social/slots.h)",
             "# group: one companion at a time per player (the hire INFO of one fires the other); every placed form is listed"]
    for name, refs in follower_groups():
        lines.append(f"group {name} {refs}")
    lines.append("# party: always a party companion. None by default: the rules engine's owner=party (Lonesome Road) names ED-E at run time")
    lines.append("# view-party: quest / object scripts that read the hired flags without hiring or firing; they see the whole party's flags")
    lines += [f"view-party {s}" for s in scripts]
    return "\n".join(lines) + "\n"


def header(text):
    if ")SETS\"" in text:
        raise SystemExit("data contains the raw-string terminator")
    return ("// generated by plugin/companions/proof/gen_sets.py from data/companion_sets.txt; do not edit\n#pragma once\nnamespace nvcoop::social {\n"
            "inline const char* kDefaultCompanionSets = R\"SETS(" + text + ")SETS\";\n}  // namespace nvcoop::social\n")


def main():
    check = "--check" in sys.argv
    if not SCRIPTS.exists():
        print("out/questdata/scripts.json.gz is missing")
        return 2
    text = build(mover_scripts())
    if check:
        ok = OUT_TXT.exists() and OUT_TXT.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        ok = ok and OUT_H.exists() and OUT_H.read_text(encoding="utf-8").replace("\r\n", "\n") == header(text)
        print("companion_sets: up to date" if ok else "companion_sets: OUT OF DATE (run gen_sets.py)")
        return 0 if ok else 1
    OUT_TXT.parent.mkdir(parents=True, exist_ok=True)
    OUT_TXT.write_text(text, encoding="utf-8", newline="\n")
    OUT_H.write_text(header(text), encoding="utf-8", newline="\n")
    print(f"wrote {OUT_TXT.relative_to(ROOT)} ({len(text)} bytes) and {OUT_H.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
